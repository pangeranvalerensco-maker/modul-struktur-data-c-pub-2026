#include <stdio.h>

int main() {
    // array integer
    int nilai[3] = {80, 85, 90};

    printf("Nilai ke-1: %d\n", nilai[0]);
    printf("Nilai ke-2: %d\n", nilai[1]);
    printf("Nilai ke-3: %d\n\n", nilai[2]);

    // array karakter (string)
    char nama[5] = "Budi";
    printf("Nama: %s\n", nama);

    return 0;
}