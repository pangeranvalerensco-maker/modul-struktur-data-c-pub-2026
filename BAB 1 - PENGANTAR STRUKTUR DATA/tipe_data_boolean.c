#include <stdio.h>
#include <stdbool.h> // digunakan untuk menyediakan tipe data bool serta nilai true dan false

int main() {

    // Mengecek apakah nilai lulus
    bool lulus = true;
    printf("Status kelulusan: %d\n\n", lulus);

    // Mengecek apakah umur sudah cukup
    bool cukupUmur = false;
    printf("Apakah cukup umur: %d\n\n", cukupUmur);

    return 0;
}