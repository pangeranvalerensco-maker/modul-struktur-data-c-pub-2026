#include <stdio.h>

int main() {

    // menyimpan karakter huruf
    char huruf = 'a';
    printf("Karakter huruf: %c\n\n", huruf);

    // menyimpan karakter angka (bukan integer)
    char angka = '7';
    printf("Karakter angka: %c\n\n", angka);

    // menyimpan karakter khusus
    char simbol = '@';
    printf("Karakter simbol: %c\n\n", simbol);

    return 0;
}